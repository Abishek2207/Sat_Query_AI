@app.get("/evaluations")
def get_evaluations():
    import os
    from pathlib import Path
    
    # We will read the evaluation results generated by the core evaluation framework
    benchmarks = ["vrsbench", "rsvqa", "cdvqa", "isro_sac"]
    results = []
    
    # We assume the backend is run from the project root CWD
    for b in benchmarks:
        path = Path(f"evaluation/{b}/results.json")
        if path.exists():
            with open(path, "r", encoding="utf-8") as f:
                results.append(json.load(f))
        else:
            results.append({
                "benchmark_name": b.upper(),
                "status": "NOT_CONFIGURED",
                "metrics": None,
                "expected_format": "Unknown",
                "dataset_path": "Unknown",
                "description": "Evaluation framework not yet run for this benchmark."
            })
            
    return {"evaluations": results}

