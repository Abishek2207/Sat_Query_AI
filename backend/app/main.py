@app.post("/analyze", response_model=AnalysisResponse)
async def analyze(
    query: str = Form(...),
    parameters: str = Form("{}"),
    benchmark_mode: bool = Form(False),
    files: List[UploadFile] = File(...),
):
    try:
        params_dict = json.loads(parameters)
    except Exception:
        params_dict = {}

    file_data = [{"filename": f.filename, "bytes": await f.read()} for f in files]

    # --- Baseline shortcut for two-image tasks ---
    # When no specialist endpoint is configured, route to local baselines
    # so the prototype produces real (non-fabricated) results immediately.
    if len(file_data) == 2:
        q = query.lower()
        if any(kw in q for kw in ["change", "difference"]):
            baseline_result = compute_change_baseline(
                file_data[0]["bytes"], file_data[1]["bytes"]
            )
            if baseline_result.get("status") != "ERROR":
                baseline_result["provenance"]["inference_timestamp"] = datetime.utcnow().isoformat() + "Z"
                baseline_result["provenance"]["input_filenames"] = [f["filename"] for f in file_data]
                return AnalysisResponse(
                    task="change_analysis",
                    answer=baseline_result["answer"],
                    status=baseline_result["status"],
                    confidence=baseline_result.get("confidence"),
                    evidence=baseline_result.get("evidence", []),
                    visual_output=baseline_result.get("visual_output"),
                    execution_trace=[
                        "VALIDATED: Both files accepted.",
                        "ROUTER: Selected task 'change_analysis'.",
                        "EXECUTION: Baseline pixel-diff applied.",
                        "EVIDENCE VALIDATOR: Spatial evidence present.",
                    ],
                    provenance=baseline_result["provenance"],
                )

        if any(kw in q for kw in ["sar", "radar", "optical"]):
            baseline_result = verify_optical_sar_pair(
                file_data[0]["bytes"], file_data[1]["bytes"]
            )
            if baseline_result.get("status") != "ERROR":
                baseline_result["provenance"]["inference_timestamp"] = datetime.utcnow().isoformat() + "Z"
                baseline_result["provenance"]["input_filenames"] = [f["filename"] for f in file_data]
                return AnalysisResponse(
                    task="optical_sar",
                    answer=baseline_result["answer"],
                    status=baseline_result["status"],
                    confidence=baseline_result.get("confidence"),
                    evidence=baseline_result.get("evidence", []),
                    visual_output=baseline_result.get("visual_output"),
                    execution_trace=[
                        "VALIDATED: Both files accepted.",
                        "ROUTER: Selected task 'optical_sar'.",
                        "EXECUTION: Metadata alignment baseline applied.",
                        "EVIDENCE VALIDATOR: Metadata evidence present.",
                    ],
                    provenance=baseline_result["provenance"],
                )

    # --- Standard LangGraph agent pipeline ---
    state = {
        "query": query,
        "files": file_data,
        "parameters": params_dict,
        "benchmark_mode": benchmark_mode,
        "trace": [],
    }

    result = await app_graph.ainvoke(state)
    api_res = result.get("api_response", {})

    return AnalysisResponse(
        task=result.get("selected_task", "unknown"),
        answer=api_res.get("answer", "ERROR"),
        status=api_res.get("status", "ERROR"),
        evidence=api_res.get("evidence", []),
        visual_output=api_res.get("visual_output"),
        confidence=api_res.get("confidence"),
        execution_trace=result.get("trace", []),
        provenance=api_res.get("provenance"),
        validation=result.get("validation_results"),
    )


